import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const root = new URL(".", import.meta.url);
const pkg = JSON.parse(readFileSync(new URL("package.json", root), "utf-8"));

describe("package.json", () => {
  it("declares the Go module path as the virtual import path", () => {
    const goMod = readFileSync(new URL("go.mod", root), "utf-8");
    const [, module] = goMod.match(/^module\s+(\S+)$/m) ?? [];

    expect(pkg["makefiles.dev"].protobuf.importPath).toBe(module);
  });

  it("exports each package directory", () => {
    const dirs = readdirSync(root, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .filter((name) =>
        readdirSync(new URL(`${name}/`, root)).includes("index.ts"),
      );

    for (const dir of dirs) {
      expect(pkg.exports, `missing export for ${dir}`).toHaveProperty([
        `./${dir}`,
      ]);
    }
  });

  // Code generated by protoc-gen-es for other schemas that import these .proto
  // files imports the generated files at their virtual import path, for
  // example "@dogmatiq/protobuf/github.com/dogmatiq/protobuf/uuidpb/uuid_pb.js",
  // when using map_imports=github.com/dogmatiq/protobuf/:@dogmatiq/protobuf.
  it("exports generated files at their import path, but not other modules", () => {
    const importPath = pkg["makefiles.dev"].protobuf.importPath;

    expect(Object.keys(pkg.exports).filter((k) => k.includes("*"))).toEqual([
      `./${importPath}/*_pb.js`,
    ]);
    expect(pkg.exports[`./${importPath}/*_pb.js`]).toEqual({
      types: "./artifacts/dist/*_pb.d.ts",
      default: "./artifacts/dist/*_pb.js",
    });
  });

  it("requires a @bufbuild/protobuf version that supports the generated code", () => {
    const range: string = pkg.peerDependencies["@bufbuild/protobuf"];
    const [, lowerBound] = range.match(/(\d+\.\d+\.\d+)/) ?? [];

    expect(lowerBound, `cannot parse lower bound of ${range}`).toBeDefined();

    for (const version of generatorVersions()) {
      expect(
        compareVersions(lowerBound, version),
        `peer dependency range ${range} allows versions older than protoc-gen-es v${version}`,
      ).toBeGreaterThanOrEqual(0);
    }
  });
});

// generatorVersions returns the versions of protoc-gen-es that produced the
// committed *_pb.ts files.
function generatorVersions(): string[] {
  const versions = new Set<string>();

  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory()) {
      continue;
    }

    for (const file of readdirSync(new URL(`${entry.name}/`, root))) {
      if (!file.endsWith("_pb.ts")) {
        continue;
      }

      const content = readFileSync(
        new URL(`${entry.name}/${file}`, root),
        "utf-8",
      );
      const [, version] =
        content.match(/^\/\/ @generated by protoc-gen-es v(\S+)/m) ?? [];

      expect(version, `cannot find generator version in ${file}`).toBeDefined();
      versions.add(version);
    }
  }

  expect(versions.size).toBeGreaterThan(0);

  return [...versions];
}

function compareVersions(a: string, b: string): number {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);

  for (let i = 0; i < 3; i++) {
    if (pa[i] !== pb[i]) {
      return pa[i] - pb[i];
    }
  }

  return 0;
}
